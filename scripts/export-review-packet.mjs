#!/usr/bin/env node
/**
 * Writes docs/clinical-review/review-packet.md: every health-information page and answer, in plain text, for
 * Dr. Paramjit Panesar, MD, to read and approve. Run: npm run export:review
 *
  * It reads src/data/content.ts directly (no build needed). The packet is generated from the same data
 * the pages use, so what Dr. Panesar approves is exactly what is published.
 *
 * Publishing: after approval, set CLINICAL_REVIEW.reviewedOn in src/data/pages.ts to the approval date.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(ROOT, 'src', 'data', 'content.ts'), 'utf8');
const pages = readFileSync(join(ROOT, 'src', 'data', 'pages.ts'), 'utf8');

if (!existsSync(join(ROOT, 'src', 'data', 'content.ts'))) {
  console.error('src/data/content.ts not found.');
  process.exit(1);
}

/** Pulls a template-literal or string value that follows `key:` or a const name, keeping ${...} readable. */
const tidy = (text) =>
  text
    .replace(/\$\{CALL\}/g, '916-236-5800')
    .replace(/\$\{ADDRESS\}/g, '8191 Timberlake Way, Suite 200, Sacramento, CA 95823')
    .replace(/\$\{DOC\}/g, 'Dr. Paramjit Panesar, MD')
    .replace(/\$\{INITIAL_VISIT_FROM\}/g, '$65')
    .replace(/\$\{DRIVE\}/g, 'about 12 minutes')
    .replace(/\$\{OFFICE\.street\}/g, '8191 Timberlake Way, Suite 200')
    .replace(/\$\{OFFICE\.streetName\}/g, 'Timberlake Way')
    .replace(/\$\{insuranceSentence\(\)\}/g, 'Aetna, Anthem Blue Cross, Blue Shield of California, Cigna, Health Net, UnitedHealthcare, Sutter Health, Hill Physicians, and Medicare')
    .replace(/\$\{LOCATION\.highway\}/g, 'Highway 99')
    .replace(/\$\{LOCATION\.hospitalDistance\}/g, '0.4 mile')
    .replace(/\$\{LOCATION\.nearHospital\}/g, 'Methodist Hospital of Sacramento')
    .replace(/\$\{LOCATION\.crossStreet\}/g, 'Bruceville Road')
    .replace(/\$\{[^}]+\}/g, '[...]')
    .replace(/\\'/g, "'");

function section(name) {
  const start = source.indexOf(`export const ${name}`);
  if (start === -1) return '';
  const next = source.indexOf('\nexport const ', start + 10);
  return source.slice(start, next === -1 ? undefined : next);
}

function directAnswer(name) {
  const m = source.match(new RegExp(`export const ${name} = \`([^\`]+)\``));
  return m ? tidy(m[1]) : '';
}

/** The FAQ items of a page section: question, answer, whether flagged as health information. */
function faqs(block) {
  const out = [];
  const re = /\{\s*question: '((?:[^'\\]|\\.)+)',\s*(clinical: true,)?\s*answer: `([^`]+)`/g;
  for (const m of block.matchAll(re)) out.push({ question: tidy(m[1]), clinical: Boolean(m[2]), answer: tidy(m[3]) });
  return out;
}

/** Blocks with `clinical: true`, with their text. */
function blocks(block) {
  const out = [];
  const re = /id: '([\w-]+)',\s*heading: '([^']+)',(\s*clinical: true,)?/g;
  for (const m of block.matchAll(re)) {
    const slice = block.slice(m.index, block.indexOf('\n    },', m.index));
    const texts = [...slice.matchAll(/'((?:[^'\\]|\\.)+)'|`([^`]+)`/g)].map((t) => tidy(t[1] ?? t[2])).filter((t) => t.length > 25 && !/^(id|heading)/.test(t));
    out.push({ id: m[1], heading: m[2], clinical: Boolean(m[3]), text: texts.filter((t) => t !== m[2]) });
  }
  return out;
}

const PAGES = [
  ['annualPhysical', 'ANNUAL_DIRECT_ANSWER', 'ANNUAL_PHYSICAL', '/annual-physical-sacramento', 'Annual physical'],
  ['sameDay', 'SAME_DAY_DIRECT_ANSWER', 'SAME_DAY', '/same-day-appointments-sacramento', 'Same-day appointments'],
  ['medicare', 'MEDICARE_DIRECT_ANSWER', 'MEDICARE', '/medicare-doctor-sacramento', 'Medicare patients'],
  ['mediCal', 'MEDI_CAL_DIRECT_ANSWER', 'MEDI_CAL', '/medi-cal-doctor-sacramento', 'Medi-Cal patients'],
  ['nivano', 'NIVANO_DIRECT_ANSWER', 'NIVANO', '/nivano-physicians-doctor-sacramento', 'Nivano Physicians patients'],
  ['selfPay', 'SELF_PAY_DIRECT_ANSWER', 'SELF_PAY', '/doctor-without-insurance-sacramento', 'Doctor without insurance'],
  ['immigration', 'IMMIGRATION_DIRECT_ANSWER', 'IMMIGRATION', '/immigration-medical-exam-sacramento', 'Immigration medical exam'],
  ['services', 'SERVICES_DIRECT_ANSWER', 'SERVICES', '/services', 'Services'],
  ['faq', 'FAQ_DIRECT_ANSWER', 'FAQ_HUB', '/faq', 'Questions hub (only the items marked HEALTH are held back)'],
];

const lines = [];
lines.push('# Clinical review packet for Dr. Paramjit Panesar, MD');
lines.push('');
lines.push('Generated by `npm run export:review` from `src/data/content.ts`. What you approve here is exactly what the website will publish.');
lines.push('');
lines.push('## What to do');
lines.push('');
lines.push('1. Read every item below. Mark anything inaccurate, outdated or not offered at your office.');
lines.push('2. In particular, confirm each statement under "Confirm before approving".');
lines.push('3. Reply with your approval and any edits. The practice then sets one date in `src/data/pages.ts` (`CLINICAL_REVIEW.reviewedOn`).');
lines.push('4. Until that date is set, these pages answer "not found" and are not in the sitemap, navigation or llms.txt, and no page claims a medical review.');
lines.push('');
lines.push('## Confirm before approving');
lines.push('');
lines.push('- Each service listed is actually offered at the office: annual physicals, school and sports physicals, vaccinations, care for diabetes and high blood pressure, USCIS immigration medical exams.');
lines.push('- Which ages the office sees (the school and sports physical text asks callers to check the child\'s age). Whether well-child exams should be added.');
lines.push('- "UAMS" is written as University of Arkansas for Medical Sciences, as the owner gave only the abbreviation.');
lines.push('- Languages spoken, telehealth and walk-in policy are NOT on the pages, because they were not confirmed.');
lines.push('- The general health statements (what an annual physical includes, fasting, Medicare Annual Wellness Visit, the three primary care specialties, vaccines for Form I-693 follow USCIS rules).');
lines.push('- The same-day page: the emergency examples (chest pain, trouble breathing, signs of a stroke, severe bleeding, serious injury) and the 988 crisis line. It states no call-by time, slot count or visit types; send those if you want them published.');
lines.push('- The Medicare page: the short description of Original Medicare, Part B and Medicare Advantage HMOs. It does not say the office accepts Medicare assignment or name any Medicare Advantage plan; send those if you want them published.');
lines.push('- The page for patients without insurance: the $65 line, the steps, and the BenefitsCal and Covered California links. It says nothing about what the $65 includes, payment methods or discounts until you confirm them.');
lines.push('- The immigration page defers to USCIS for who needs the exam, vaccine requirements and how to submit the form. It gives no fee. Add a fee only if you want one published.');
lines.push('');
lines.push('Not medical advice line shown on every health page: "This page is general information, not medical advice. For advice about your own health, talk to a clinician or call 916-236-5800. In an emergency, call 911."');
lines.push('');

for (const [key, daName, constName, path, label] of PAGES) {
  const block = section(constName);
  const entryStart = pages.indexOf(`  ${key}: {`);
  const entry = pages.slice(entryStart, pages.indexOf('\n  },', entryStart));
  const clinicalPage = /clinical: true/.test(entry);
  lines.push(`## ${label}  (${path})`);
  lines.push('');
  lines.push(`Page status: ${clinicalPage ? 'HEALTH PAGE, held until you approve' : 'live now; only the items marked HEALTH below are held'}.`);
  lines.push('');
  const da = directAnswer(daName);
  if (da) {
    lines.push('**Direct answer under the heading**');
    lines.push('');
    lines.push(`> ${da}`);
    lines.push('');
  }
  const blks = blocks(block).filter((b) => clinicalPage || b.clinical);
  for (const b of blks) {
    lines.push(`**${b.heading}**${b.clinical ? ' (HEALTH)' : ''}`);
    lines.push('');
    for (const t of b.text) lines.push(`- ${t}`);
    lines.push('');
  }
  const items = faqs(block).filter((f) => clinicalPage || f.clinical);
  if (items.length) {
    lines.push('**Questions and answers**');
    lines.push('');
    for (const f of items) {
      lines.push(`Q${f.clinical ? ' (HEALTH)' : ''}: ${f.question}`);
      lines.push('');
      lines.push(`A: ${f.answer}`);
      lines.push('');
    }
  }
}

lines.push('## Approval');
lines.push('');
lines.push('Reviewed and approved by: ______________________  Dr. Paramjit Panesar, MD');
lines.push('');
lines.push('Date: ______________   Edits requested: ____________________________________________');
lines.push('');

const out = join(ROOT, 'docs', 'clinical-review');
mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'review-packet.md'), `${lines.join('\n')}\n`, 'utf8');
console.log(`Wrote docs/clinical-review/review-packet.md (${lines.length} lines)`);
